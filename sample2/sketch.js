function setup() {
  createCanvas(600, 400);
}

function draw() {
  // 0. 따뜻한 우주 배경 (도화지)
  background(245, 240, 235);

  noStroke();

  // 1. 거대한 행성들 (원형 활용)
  fill(210, 150, 130); ellipse(180, 150, 200, 200); // 붉은빛 행성
  fill(160, 190, 200); ellipse(420, 220, 280, 280); // 푸른빛 행성
  fill(235, 205, 120); ellipse(320, 100, 150, 150); // 노란빛 달
  fill(180, 200, 180); ellipse(120, 320, 180, 180); // 초록빛 별

  // 2. 미지의 우주선들 (삼각형 활용)
  fill(40, 40, 45); triangle(50, 380, 200, 250, 280, 390); // 비행체 1
  fill(220, 100, 80); triangle(450, 50, 580, 120, 400, 180); // 비행체 2

  // 3. 인공위성 및 정거장 (사각형 활용)
  rectMode(CENTER);
  fill(50, 90, 140); rect(300, 190, 140, 140); // 중심 우주 정거장
  fill(230, 200, 80); rect(130, 90, 80, 80);   // 소형 위성

  // 4. 행성 간의 궤도와 유성우 (선 활용)
  stroke(40, 40, 45);
  strokeWeight(5); line(30, 30, 570, 370); // 메인 궤도
  strokeWeight(3); line(100, 380, 520, 60);

  stroke(220, 100, 80);
  strokeWeight(2); line(20, 200, 580, 180);

  stroke(50, 90, 140);
  strokeWeight(4); line(350, 20, 300, 390);

  // 5. 우주 공간의 빛나는 조각들과 작은 별들 (작은 원 겹치기 패턴)
  noStroke();
  fill(40, 40, 45);
  ellipse(320, 100, 25, 25); ellipse(200, 250, 18, 18);
  ellipse(520, 60, 30, 30); ellipse(100, 380, 20, 20);

  // 안쪽에 밝은 색을 채워 반짝이는 효과
  fill(250, 250, 250);
  ellipse(320, 100, 10, 10); ellipse(200, 250, 6, 6);
  ellipse(520, 60, 12, 12); ellipse(100, 380, 8, 8);

  fill(220, 100, 80); ellipse(400, 300, 40, 40); // 붉은 혜성
  fill(245, 240, 235); ellipse(400, 300, 15, 15);
}
